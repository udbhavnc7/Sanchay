package com.ivy.design.system.spacing

/**
 * Sanchay Radius System
 * 
 * Pre-defined radius tokens used throughout the design system.
 * Establishes consistent rounded corners for buttons, cards, inputs, etc.
 * 
 * Principle: Rounded surfaces intelligently - not every component excessively rounded.
 */
object SanchayRadius {
    val Tiny: Dp = 4.dp
    val Small: Dp = 8.dp
    val Medium: Dp = 12.dp
    val Large: Dp = 16.dp
    val Pill: Dp = 9999.dp
}